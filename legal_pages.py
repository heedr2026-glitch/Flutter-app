def _s(heading: str, *parts: str) -> str:
    return f"<section><h2>{heading}</h2>{''.join(parts)}</section>"


def _ul(*items: str) -> str:
    return "<ul>" + "".join(f"<li>{i}</li>" for i in items) + "</ul>"


